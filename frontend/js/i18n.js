let currentLang = localStorage.getItem("hanu_lang") || "en";

function applyTranslations() {
  const dict = translations[currentLang] || translations.en;
  
  // Update Page Title
  const titleEl = document.getElementById("pageTitle");
  if (titleEl && typeof currentPage !== "undefined") {
    titleEl.innerText = dict[currentPage] || currentPage;
  }
  
  // Update elements with data-i18n attributes
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      if (el.tagName === "INPUT" && el.placeholder !== undefined) {
        el.placeholder = dict[key];
      } else {
        el.innerText = dict[key];
      }
    }
  });

  // Update nav items
  document.querySelectorAll(".nav-item").forEach(item => {
    const page = item.dataset.page;
    if (page && dict[page]) {
      const textSpan = item.querySelector("[data-i18n]");
      if (textSpan) {
        textSpan.innerText = dict[page];
      }
    }
  });
}

function changeLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("hanu_lang", lang);
  applyTranslations();
  
  // Also update any language selector dropdowns if present
  document.querySelectorAll(".lang-selector").forEach(sel => {
    sel.value = lang;
  });
}

// Initial apply
document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang-selector").forEach(sel => {
    sel.value = currentLang;
  });
  applyTranslations();
});
